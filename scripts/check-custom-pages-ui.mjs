/** Mutating UI regression: run only against an isolated local database clone.
 * Creates, publishes, revises, restores and unpublishes one disposable page. */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '../apps/worker/node_modules/playwright-core/index.mjs';
import { installedChromium } from './chromium-path.mjs';
const origin = process.env.UI_TEST_ORIGIN || 'http://127.0.0.1:4175';
if (!['127.0.0.1', 'localhost'].includes(new URL(origin).hostname) || process.env.UI_TEST_ISOLATED !== '1') throw new Error('Set UI_TEST_ISOLATED=1 and use a local server connected to a disposable database.');
const slug = `ui-review-${Date.now()}`;
const title = `UI review ${slug}`;
const screenshotDir = '/private/tmp/deep-fryer-high-effort-visuals';
await mkdir(screenshotDir, { recursive: true });
const browser = await chromium.launch({ executablePath: installedChromium(chromium.executablePath()) });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${origin}/nyc/admin/pages`, { waitUntil: 'networkidle' });
  const create = page.locator('section').filter({ has: page.getByRole('heading', { name: 'Create a page', exact: true }) });
  await create.getByLabel('Page title', { exact: true }).fill(title);
  await create.getByLabel('URL name', { exact: true }).fill(slug);
  await create.getByLabel('Page content', { exact: true }).fill('# Community priorities\n\n- A readable local plan\n- Sources residents can inspect\n\n[Official source](https://example.gov)\n\n<script>window.untrustedExecuted=true</script>');
  await create.getByText('Preview draft', { exact: true }).click();
  assert.equal(await page.evaluate(() => window.untrustedExecuted), undefined);
  await page.screenshot({ path: `${screenshotDir}/custom-pages-editor-desktop.png` });
  await create.getByRole('button', { name: 'Save draft', exact: true }).click();
  const card = page.locator('section').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  await card.getByText('Version history', { exact: true }).waitFor();
  await card.getByRole('button', { name: 'Publish this version', exact: true }).click();
  await card.getByRole('link', { name: 'View public page', exact: false }).waitFor();
  const publicPage = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await publicPage.goto(`${origin}/nyc/pages/${slug}`, { waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByRole('heading', { level: 1 }).innerText(), title);
  assert.equal(await publicPage.evaluate(() => window.untrustedExecuted), undefined);
  assert.ok(await publicPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await publicPage.screenshot({ path: `${screenshotDir}/custom-page-public-mobile.png` });
  await card.getByLabel('Page content', { exact: true }).fill('Second draft version');
  await card.getByRole('button', { name: 'Save a new draft version', exact: true }).click();
  await card.getByText(`Version 2 · ${title}`, { exact: true }).waitFor();
  await publicPage.reload({ waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByText('Second draft version', { exact: true }).count(), 0, 'Saving does not publish');
  await card.getByRole('button', { name: 'Publish this version', exact: true }).click();
  await card.getByRole('status').filter({ hasText: 'Version 2 is now published.' }).waitFor();
  await publicPage.reload({ waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByText('Second draft version', { exact: true }).count(), 1);
  await card.getByRole('button', { name: 'Restore and publish this version', exact: true }).click();
  await card.getByRole('status').filter({ hasText: 'Version 1 is now published.' }).waitFor();
  await publicPage.reload({ waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByRole('heading', { name: 'Community priorities', exact: true }).count(), 1);
  await card.getByRole('button', { name: 'Remove from public site', exact: true }).click();
  await card.getByRole('status').filter({ hasText: 'Removed from the public site.' }).waitFor();
  await publicPage.reload({ waitUntil: 'networkidle' });
  assert.equal(await publicPage.getByRole('heading', { name: 'Page not found', exact: true }).count(), 1);
  await page.setViewportSize({ width: 320, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await card.getByRole('heading', { name: title, exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: `${screenshotDir}/custom-pages-editor-mobile.png` });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: true, slug, checks: ['safe Markdown preview', 'immutable version save', 'explicit publish', 'draft privacy', 'restore old version', 'reversible unpublish', '320px editor and 390px public page'] }));
} finally { await browser.close(); }
