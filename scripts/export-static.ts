#!/usr/bin/env tsx
/**
 * Static export (SPEC §5 dashboard path): render every tenant's published
 * portrait as the self-contained canvas dashboard — the same index.html/
 * doughnut.js/app.js the Santa Cruz GitHub Pages site runs, with data.js
 * generated from deep-fryer's published versions and evidence copied in.
 * The retired agent-chat UI is stripped (no AI on the public plane).
 *
 * Usage: export-static --site /path/to/doughnut-santa-cruz/docs --out ./static-export
 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { eq, isNotNull } from 'drizzle-orm';
import { formatIndicatorValue } from '@deep-fryer/core';
import { dimensions, dimensionVersions, getDb, tenants } from '@deep-fryer/db';

interface ExportEntry {
  name: string;
  level: number | null;
  indicator?: string;
  value?: string | number | null;
  year?: number | null;
  target?: string | number | null;
  context?: string;
  source?: string;
  sourceUrl?: string;
  screenshot: string | null;
  actions: string[];
}

function parseArgs(argv: string[]) {
  const get = (flag: string, fallback?: string) => {
    const idx = argv.indexOf(flag);
    return idx >= 0 ? argv[idx + 1] : fallback;
  };
  const site = get('--site');
  if (!site) {
    console.error('Usage: export-static --site <doughnut-santa-cruz/docs path> [--out ./static-export]');
    process.exit(1);
  }
  return { site, out: get('--out', './static-export') as string };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const db = getDb();
  await mkdir(path.join(args.out, 'img'), { recursive: true });

  const allTenants = await db.select().from(tenants);
  const jurisdictions: Record<string, unknown> = {};
  const tabs: { key: string; name: string }[] = [];

  for (const tenant of allTenants) {
    const dims = await db
      .select({ dimension: dimensions, version: dimensionVersions })
      .from(dimensions)
      .innerJoin(dimensionVersions, eq(dimensions.publishedVersionId, dimensionVersions.id))
      .where(eq(dimensions.tenantId, tenant.id));
    if (dims.length === 0) continue;
    dims.sort((a, b) => a.dimension.displayOrder - b.dimension.displayOrder);

    const toEntry = async ({ dimension, version }: (typeof dims)[number]): Promise<ExportEntry> => {
      const ind = version.data.indicators[0];
      let screenshot: string | null = null;
      const snapshotPath = ind?.evidence?.snapshot_path;
      if (snapshotPath) {
        const local = path.join(
          process.cwd(), 'apps', 'web', 'public', 'evidence', tenant.slug, snapshotPath,
        );
        if (existsSync(local)) {
          const dest = `${tenant.slug}_${path.basename(snapshotPath)}`;
          await copyFile(local, path.join(args.out, 'img', dest));
          screenshot = `img/${dest}`;
        }
      }
      return {
        name: version.data.name,
        level: version.vizLevel,
        indicator: ind?.name,
        value: ind ? formatIndicatorValue(ind.value, ind.unit) : undefined,
        year: ind?.year,
        target: ind ? formatIndicatorValue(ind.target, ind.unit) : undefined,
        context: version.data.context,
        source: ind?.source,
        sourceUrl: ind?.source_url,
        screenshot,
        actions: version.data.actions,
      };
    };

    jurisdictions[tenant.slug] = {
      name: tenant.name,
      population: tenant.population ? `~${tenant.population.toLocaleString('en-US')}` : '',
      description: tenant.description ?? '',
      ecological: await Promise.all(
        dims.filter((d) => d.dimension.ring === 'ecological').map(toEntry),
      ),
      social: await Promise.all(dims.filter((d) => d.dimension.ring === 'social').map(toEntry)),
    };
    tabs.push({ key: tenant.slug, name: tenant.name });
  }

  if (tabs.length === 0) throw new Error('no tenants with published portraits');

  await writeFile(
    path.join(args.out, 'data.js'),
    `// Generated by deep-fryer export-static from published portrait versions.\n` +
      `// Level scale: -100 = no problem, 0 = on track, 100 = out of control, 150 = severe, null = unknown\n` +
      `const JURISDICTIONS = ${JSON.stringify(jurisdictions, null, 2)};\n`,
  );

  await copyFile(path.join(args.site, 'doughnut.js'), path.join(args.out, 'doughnut.js'));

  // app.js hardcodes the original default jurisdiction key and keyboard
  // shortcuts; retarget them at the exported tenants.
  const firstKey = tabs[0]!.key;
  let appJs = await readFile(path.join(args.site, 'app.js'), 'utf8');
  appJs = appJs.replaceAll("'city_santa_cruz'", `'${firstKey}'`).replaceAll('"city_santa_cruz"', `"${firstKey}"`);
  for (const [i, tab] of tabs.entries()) {
    appJs = appJs.replace(
      new RegExp(`if \\(e\\.key === '${i + 1}'\\) loadDoughnut\\('[^']+'\\);`),
      `if (e.key === '${i + 1}') loadDoughnut('${tab.key}');`,
    );
  }
  await writeFile(path.join(args.out, 'app.js'), appJs);

  let html = await readFile(path.join(args.site, 'index.html'), 'utf8');
  html = html.replace(/^\s*<script src="agent-ui\.js"><\/script>\n/m, '');
  html = html.replace(
    /<div class="jurisdiction-switcher">[\s\S]*?<\/div>/,
    `<div class="jurisdiction-switcher">\n` +
      tabs
        .map(
          (t, i) =>
            `                <button class="jurisdiction-btn${i === 0 ? ' active' : ''}" data-key="${t.key}">${t.name}</button>`,
        )
        .join('\n') +
      `\n            </div>`,
  );
  // Footer links point at pages this export does not include; the AI
  // Settings link belongs to the stripped agent chat.
  html = html.replace(/<a href="(research|outreach|index-d3|energy-deepdive)\.html"[^<]*<\/a>/g, '');
  html = html.replace(/<a href="#"[^>]*AgentUI\.showSettings\(\)[^<]*<\/a>/g, '');
  await writeFile(path.join(args.out, 'index.html'), html);

  console.log(`Exported ${tabs.length} portraits to ${args.out}: ${tabs.map((t) => t.key).join(', ')}`);
}

main()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error(err);
    process.exit(1);
  });
